"""Local Bridge gateway proof for a *client principal*, separate from agent/task IDs.

The client identity is deliberately generated by the trusted Windows Bridge
gateway, never accepted from a chat or Hub request. The local owner's 256-bit
key is created by the local Bridge gateway during its first authenticated
Hub request. It is never returned to a remote agent.
Same-user Windows processes are in the same OS trust domain; this does not
attest a particular remote ChatGPT account or distinguish clients behind the
same authenticated Windows Bridge endpoint.
"""
from __future__ import annotations

import hashlib
import hmac
import json
from pathlib import Path
import os
import secrets
import time
from typing import Any

PRINCIPAL = "bridge-chatgpt-connector"
PROOF_FIELD = "_gateway_attestation"
KEY_FILENAME = "bridge-client-principal.key"
MAX_AGE_SECONDS = 30


def _key(state_dir: str | Path) -> bytes | None:
    path = Path(state_dir) / KEY_FILENAME
    try:
        raw = path.read_text(encoding="ascii").strip()
        key = bytes.fromhex(raw)
        if len(key) == 32:
            return key
    except (ValueError, OSError, UnicodeError):
        pass
    return None



def ensure_gateway_key(state_dir: str | Path) -> bool:
    """One-time local Bridge gateway initialization; no request-supplied grants.

    Only the trusted Bridge gateway invokes this during an authenticated Bridge
    call. The Hub itself never creates the file or trusts an unsigned request.
    An invalid or unreadable existing file is a hard failure, not auto-replaced.
    Returns True only if this call created the local key.
    """
    path = Path(state_dir) / KEY_FILENAME
    if _key(state_dir) is not None:
        return False
    if path.exists():
        raise ValueError("GATEWAY_KEY_INVALID")
    path.parent.mkdir(parents=True, exist_ok=True)
    try:
        fd = os.open(str(path), os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    except FileExistsError:
        if _key(state_dir) is not None:
            return False
        raise ValueError("GATEWAY_KEY_INVALID") from None
    try:
        key = secrets.token_bytes(32)
        with os.fdopen(fd, "w", encoding="ascii") as stream:
            stream.write(key.hex() + "\n")
            stream.flush()
            os.fsync(stream.fileno())
        try:
            os.chmod(path, 0o600)
        except OSError:
            pass
        if _key(state_dir) is None:
            raise ValueError("GATEWAY_KEY_NOT_VERIFIED")
    except BaseException:
        try:
            path.unlink()
        except OSError:
            pass
        raise
    return True

def _payload(request: dict[str, Any], *, issued_at: int, nonce: str) -> bytes:
    bare = {k: v for k, v in request.items() if k != PROOF_FIELD}
    return json.dumps({
        "schema": "ff-bridge-client-principal-v1",
        "principal": PRINCIPAL,
        "issued_at": issued_at,
        "nonce": nonce,
        "request": bare,
    }, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False).encode("utf-8")


def sign_gateway_request(request: dict[str, Any], state_dir: str | Path, *, now: int | None = None) -> dict[str, Any]:
    """Gateway-only: add short-lived proof; a missing key alone is not trusted."""
    if not isinstance(request, dict) or PROOF_FIELD in request:
        raise ValueError("GATEWAY_ATTESTATION_CALLER_FORBIDDEN")
    key = _key(state_dir)
    if key is None:
        return dict(request)
    timestamp = int(time.time() if now is None else now)
    nonce = secrets.token_hex(16)
    digest = hmac.new(key, _payload(request, issued_at=timestamp, nonce=nonce), hashlib.sha256).hexdigest()
    return {**request, PROOF_FIELD: {
        "schema": "ff-bridge-client-principal-v1",
        "principal": PRINCIPAL,
        "issued_at": timestamp,
        "nonce": nonce,
        "signature": digest,
    }}


def verify_gateway_request(request: dict[str, Any], state_dir: str | Path, *, now: int | None = None) -> str | None:
    """Hub-only: fail closed on invalid proof; no proof means no trusted principal."""
    if not isinstance(request, dict):
        raise ValueError("GATEWAY_ATTESTATION_INVALID")
    proof = request.get(PROOF_FIELD)
    if proof is None:
        return None
    if not isinstance(proof, dict) or set(proof) != {"schema", "principal", "issued_at", "nonce", "signature"}:
        raise ValueError("GATEWAY_ATTESTATION_INVALID")
    stamp = proof.get("issued_at")
    nonce = proof.get("nonce")
    signature = proof.get("signature")
    if (proof.get("schema") != "ff-bridge-client-principal-v1"
        or proof.get("principal") != PRINCIPAL
        or type(stamp) is not int
        or abs(int(time.time() if now is None else now) - stamp) > MAX_AGE_SECONDS
        or not isinstance(nonce, str) or len(nonce) != 32
        or any(ch not in "0123456789abcdef" for ch in nonce)
        or not isinstance(signature, str) or len(signature) != 64):
        raise ValueError("GATEWAY_ATTESTATION_INVALID")
    key = _key(state_dir)
    if key is None:
        raise ValueError("GATEWAY_ATTESTATION_INVALID")
    try:
        expected = hmac.new(key, _payload(request, issued_at=stamp, nonce=nonce), hashlib.sha256).hexdigest()
    except (TypeError, ValueError):
        raise ValueError("GATEWAY_ATTESTATION_INVALID") from None
    if not hmac.compare_digest(signature, expected):
        raise ValueError("GATEWAY_ATTESTATION_INVALID")
    return PRINCIPAL
